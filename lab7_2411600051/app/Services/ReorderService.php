<?php

namespace App\Services;

use App\Models\InventoryTransaction;
use App\Models\Product;
use App\Models\PurchaseOrder;
use App\Models\PurchaseOrderItem;
use App\Models\User;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;

class ReorderService
{
    protected int $defaultLookbackDays = 30;
    protected int $defaultSafetyStock = 10;

    public function calculateReorderPoint(Product $product): int
    {
        $averageDailyUsage = $this->calculateAverageDailyUsage($product);
        $leadTime = $product->supplier->lead_time_days ?? 7;
        $safetyStock = $this->defaultSafetyStock;

        return (int) ceil(($averageDailyUsage * $leadTime) + $safetyStock);
    }

    public function calculateOptimalOrderQuantity(Product $product): int
    {
        $averageDailyUsage = $this->calculateAverageDailyUsage($product);
        $leadTime = $product->supplier->lead_time_days ?? 7;

        $suggested = (int) ceil($averageDailyUsage * $leadTime * 2);
        $suggested = max($suggested, $product->reorder_level);

        return $suggested;
    }

    public function getProductsNeedingReorder()
    {
        return Product::with('supplier')->get()->filter(function ($product) {
            return $product->quantity <= $this->calculateReorderPoint($product);
        });
    }

    public function groupProductsBySupplier($products)
    {
        return $products->filter(function ($product) {
            return $product->supplier_id !== null;
        })->groupBy('supplier_id');
    }

    public function generatePurchaseOrders(): array
    {
        $products = $this->getProductsNeedingReorder();
        $grouped = $this->groupProductsBySupplier($products);
        $createdOrders = [];

        foreach ($grouped as $supplierId => $supplierProducts) {
            $order = DB::transaction(function () use ($supplierId, $supplierProducts) {
                $purchaseOrder = PurchaseOrder::create([
                    'reference_number' => PurchaseOrder::generateReferenceNumber(),
                    'supplier_id' => $supplierId,
                    'status' => 'draft',
                    'order_date' => now(),
                    'notes' => 'Auto-generated by scheduled reorder check.',
                    'created_by' => User::first()?->id,
                ]);

                foreach ($supplierProducts as $product) {
                    PurchaseOrderItem::create([
                        'purchase_order_id' => $purchaseOrder->id,
                        'product_id' => $product->id,
                        'quantity_ordered' => $this->calculateOptimalOrderQuantity($product),
                        'unit_price' => $product->unit_price,
                    ]);
                }

                $purchaseOrder->calculateTotal();

                return $purchaseOrder;
            });

            $createdOrders[] = $order;
        }

        Log::info('ReorderService: generated ' . count($createdOrders) . ' draft purchase order(s).');

        return $createdOrders;
    }

    protected function calculateAverageDailyUsage(Product $product): float
    {
        $since = now()->subDays($this->defaultLookbackDays);

        $totalOut = InventoryTransaction::where('product_id', $product->id)
            ->where('type', 'stock_out')
            ->where('created_at', '>=', $since)
            ->sum('quantity');

        $totalOut = abs($totalOut);

        if ($totalOut === 0) {
            return 1;
        }

        return round($totalOut / $this->defaultLookbackDays, 2);
    }
}
